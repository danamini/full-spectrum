#!/usr/bin/env python3
"""Download the spectral reference datasets and write them as ES modules in data/.

Usage (run isolated, raw downloads kept outside the repo):
    python3 -I tools/build_spectral_data.py --raw "$(mktemp -d)" --repo .

Writes data/cie1931.js, data/cones.js, data/lines.js, data/solar.js.
Sources and licences: docs/credits-spectral.md. Python 3 standard library only.
Downloaded files are treated as data: parsed as CSV/text, never executed or imported.
"""
