def build_lines(raw, repo):
    spectra = {}

    def get(sp):
        if sp not in spectra:
            spectra[sp] = nist_lines(raw, sp)
        return spectra[sp]

    emission = {}
    for el, sp, keep in EMISSION_SET:
        best = {}
        for wl, inten, _ in get(sp):
            if inten is None or inten <= 0 or not 380 <= wl <= 750:
                continue
            k = round(wl, 3)  # NIST repeats a blended line once per component
            best[k] = max(best.get(k, 0), inten)
        top = sorted(best.items(), key=lambda kv: -kv[1])[:keep]
        peak = top[0][1]
        emission[el] = sorted((wl, i / peak) for wl, i in top)

    fh = []
    misses = []
    for name, el, sp, approx, note in FRAUNHOFER:
        if sp is None:
            fh.append((name, approx, el, note, 'table', True))
            continue
        # prefer an observed line; fall back to a Ritz (calculated) wavelength
        cand = [(kind != 'obs', abs(wl - approx), wl, kind) for wl, _, kind in get(sp)
                if abs(wl - approx) <= 0.01]
        _, d, wl, kind = min(cand) if cand else (True, 1.0, approx, '')
        if d > 0.01:
            misses.append((name, sp, approx, wl))
            fh.append((name, approx, el, note, 'table', False))
        else:
            fh.append((name, wl, el, note, f'NIST {sp} ({kind})', False))

    lines = [HEADER,
             '// Visible emission lines, air wavelengths (nm), from the NIST Atomic Spectra Database (SRD 78).\n'
             '// rel = NIST relative intensity normalised to the strongest kept line of each element (0-1).\n'
             '// NIST intensities depend on the light source used; compare within an element, not across.\n'
             'export const EMISSION = {\n']
    for el, rows in emission.items():
        lines.append(f'  {el}: [' + ','.join(f'[{fixed(w, 4)},{num(r, 3)}]' for w, r in rows) + '],\n')
    lines.append('};\n\n')
    lines.append('// Fraunhofer lines. Designations: conventional table (credits). nm: NIST ASD air wavelength,\n'
                 '// or the tabulated value where src is "table" (O2 bands are molecular, not in the atomic database).\n'
                 'export const FRAUNHOFER = [\n')
    for name, wl, el, note, src, tell in fh:
        extra = ', telluric: true' if tell else ''
        lines.append(f'  {{ name: {js_str(name)}, nm: {fixed(wl, 4)}, element: {js_str(el)}, '
                     f'note: {js_str(note)}, src: {js_str(src)}{extra} }},\n')
    lines.append('];\n')
    write(repo, 'lines.js', ''.join(lines))
    return {'emission': emission, 'fraunhofer': fh, 'fraunhofer_misses': misses}


# ---------- ASTM G173 ----------

def bin_mean(xs, ys, a, b):
    """Mean of the piecewise-linear curve (xs, ys) over [a, b] clipped to the data range."""
    a, b = max(a, xs[0]), min(b, xs[-1])
    total = 0.0
    for i in range(len(xs) - 1):
        x0, x1 = xs[i], xs[i + 1]
        lo, hi = max(a, x0), min(b, x1)
        if hi <= lo:
            continue
        f = lambda x: ys[i] + (ys[i + 1] - ys[i]) * (x - x0) / (x1 - x0)
        total += (f(lo) + f(hi)) / 2 * (hi - lo)
    return total / (b - a)


def trapz(xs, ys):
    return sum((xs[i + 1] - xs[i]) * (ys[i] + ys[i + 1]) / 2 for i in range(len(xs) - 1))


def build_solar(raw, repo):
    data = fetch(G173_URL, os.path.join(raw, 'astmg173.zip'))
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        text = z.read('ASTMG173.csv').decode('latin-1')
    rows = list(csv.reader(io.StringIO(text)))
    assert rows[0][0].startswith('ASTM G173-03'), rows[0]
    assert 'Etr' in rows[1][1] and 'Global tilt' in rows[1][2], rows[1]
    wl, etr, glob = [], [], []
    for r in rows[2:]:
        if len(r) >= 3 and r[0].strip():
            wl.append(float(r[0])); etr.append(float(r[1])); glob.append(float(r[2]))
    grid = list(range(280, 1001)) + list(range(1010, 4001, 10))
    am0, am15 = [], []
    for g in grid:
        half = 0.5 if g <= 1000 else 5
        am0.append(bin_mean(wl, etr, g - half, g + half))
        am15.append(bin_mean(wl, glob, g - half, g + half))
    src = ('ASTM G173-03 reference spectra (SMARTS2 v2.9.2, Gueymard), via NLR (formerly NREL); '
           'bin-averaged to 1 nm (280-1000 nm) and 10 nm (1010-4000 nm), W m^-2 nm^-1')
    write(repo, 'solar.js', HEADER +
          f'export const SOLAR = {{ source: {js_str(src)},\n'
          f'nm: {arr(grid, str)},\nam0: {arr(am0)},\nam15g: {arr(am15)} }};\n')
    # integrals: original data, and the kept grid treated as bins
    widths = [1.0 if g <= 1000 else 10.0 for g in grid]
    widths[0] = 0.5; widths[grid.index(1000)] = 0.5 + 5; widths[-1] = 5
    return {
        'am0_integral_source': trapz(wl, etr), 'am15g_integral_source': trapz(wl, glob),
        'am0_integral_kept': sum(w * v for w, v in zip(widths, am0)),
        'am15g_integral_kept': sum(w * v for w, v in zip(widths, am15)),
        'solar_points': len(grid),
    }


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--raw', required=True, help='directory for raw downloads (outside the repo)')
    ap.add_argument('--repo', default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument('--only', nargs='*', choices=['cie', 'cones', 'lines', 'solar'])
    args = ap.parse_args()
    raw = os.path.abspath(args.raw)
    repo = os.path.abspath(args.repo)
    if raw == repo or raw.startswith(repo + os.sep):
        sys.exit('--raw must be outside the repo')
    os.makedirs(raw, exist_ok=True)
    os.makedirs(os.path.join(repo, 'data'), exist_ok=True)
    steps = {'cie': build_cie, 'cones': build_cones, 'lines': build_lines, 'solar': build_solar}
    for name in args.only or steps:
        result = steps[name](raw, repo)
        for k, v in result.items():
            print(f'  {k}: {v}')


if __name__ == '__main__':
    main()
