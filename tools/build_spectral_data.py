CIE_URL = 'https://files.cie.co.at/Publications-datasets/CIE_xyz_1931_2deg.csv'
CIE_SHA256 = 'fa663e3535a7e0763a745993a1f0a192eb0275ac46ad2d1befd7626841e713c1'
CONES_URL = 'http://cvrl.ucl.ac.uk/database/data/cones/linss2_10e_1.csv'
# NREL became the National Laboratory of the Rockies (NLR) in 2025; www.nrel.gov no longer resolves.
G173_URL = 'https://www.nlr.gov/media/docs/libraries/grid/zip/astmg173.zip?sfvrsn=1ef05e45_5'
NIST_URL = 'https://physics.nist.gov/cgi-bin/ASD/lines1.pl'

UA = {'User-Agent': 'full-spectrum data builder (python urllib)'}


def fetch(url, path):
    if not os.path.exists(path):
        req = urllib.request.Request(url, headers=UA)
        with urllib.request.urlopen(req, timeout=120) as r, open(path, 'wb') as f:
            f.write(r.read())
    with open(path, 'rb') as f:
        return f.read()


def num(v, sig=4):
    """Compact JS number literal with `sig` significant figures."""
    if v == 0:
        return '0'
    s = f'{v:.{sig}g}'
    if 'e' in s:
        m, e = s.split('e')
        if '.' in m:
            m = m.rstrip('0').rstrip('.')
        s = f'{m}e{int(e)}'
    elif '.' in s:
        s = s.rstrip('0').rstrip('.')
    if s.startswith('0.'):
        s = s[1:]
    elif s.startswith('-0.'):
        s = '-' + s[2:]
    return s


def fixed(v, dp):
    s = f'{v:.{dp}f}'.rstrip('0').rstrip('.')
    return s


def arr(vals, fmt=num):
    return '[' + ','.join(fmt(v) for v in vals) + ']'


def js_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def write(repo, name, text):
    path = os.path.join(repo, 'data', name)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'wrote {path} ({os.path.getsize(path)} bytes)')


HEADER = '// Generated by tools/build_spectral_data.py. Do not edit by hand. Sources: docs/credits-spectral.md\n'


# ---------- CIE 1931 ----------

def build_cie(raw, repo):
    data = fetch(CIE_URL, os.path.join(raw, 'CIE_xyz_1931_2deg.csv'))
    digest = hashlib.sha256(data).hexdigest()
    if digest != CIE_SHA256:
        sys.exit(f'CIE file checksum mismatch: {digest}')
    rows = [r for r in csv.reader(io.StringIO(data.decode('ascii'))) if r]
    nm = [int(float(r[0])) for r in rows]
    assert nm == list(range(360, 831)), 'unexpected CIE wavelength grid'
    x, y, z = ([float(r[i]) for r in rows] for i in (1, 2, 3))
    src = ('CIE 1931 2° colour-matching functions, CIE dataset doi:10.25039/CIE.DS.xvudnb9b '
           '(CIE 018:2019 Table 6), CC BY-SA 4.0')
    write(repo, 'cie1931.js', HEADER +
          f'export const CIE1931 = {{ source: {js_str(src)}, start: 360, step: 1,\n'
          f'x: {arr(x)},\ny: {arr(y)},\nz: {arr(z)} }};\n')
    i = y.index(max(y))
    return {'cie_y_peak_nm': nm[i], 'cie_y_peak': y[i], 'cie_y_555': y[nm.index(555)]}


