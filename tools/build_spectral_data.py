def js_value(v):
    if v is None:
        return 'null'
    if isinstance(v, str):
        return js_str(v)
    if isinstance(v, list):
        return '[' + ', '.join(js_value(x) for x in v) + ']'
    return str(v)


def build_cones(raw, repo):
    data = fetch(CONES_URL, os.path.join(raw, 'linss2_10e_1.csv')).decode('ascii')
    rows = [r for r in csv.reader(io.StringIO(data)) if r and r[0].strip()]
    nm = [int(float(r[0])) for r in rows]
    start = nm[0]
    assert nm == list(range(start, start + len(nm))), 'unexpected cone wavelength grid'
    # S-cone column is blank above ~615 nm in the CVRL file: treat as zero (below 4 s.f. of its peak).
    cols = [[float(r[i]) if i < len(r) and r[i].strip() else 0.0 for r in rows] for i in (1, 2, 3)]
    src = ('Stockman & Sharpe (2000) 2° cone fundamentals, linear energy, normalised to peak 1 '
           '(CVRL linss2_10e_1), http://cvrl.ucl.ac.uk')
    animals = ',\n'.join('  { ' + ', '.join(f'{k}: {js_value(v)}' for k, v in a.items()) + ' }'
                         for a in ANIMALS)
    write(repo, 'cones.js', HEADER +
          f'export const CONES = {{ source: {js_str(src)}, start: {start}, step: 1,\n'
          f'l: {arr(cols[0])},\nm: {arr(cols[1])},\ns: {arr(cols[2])} }};\n\n'
          '// Peak sensitivities from the cited peer-reviewed papers. peaksNm: receptor peaks;\n'
          '// rangeNm: wavelength span the receptors cover; rangeUm: null where the source gives no range.\n'
          f'export const ANIMALS = [\n{animals}\n];\n')
    peaks = {k: nm[c.index(max(c))] for k, c in zip('lms', cols)}
    return {'cone_peaks_nm': peaks, 'cone_range': (nm[0], nm[-1])}


# ---------- NIST lines ----------

def nist_query(spectrum, lo, hi):
    q = {
        'spectra': spectrum, 'limits_type': 0, 'low_w': lo, 'upp_w': hi, 'unit': 1, 'de': 0,
        'format': 2, 'line_out': 0, 'remove_js': 'on', 'en_unit': 0, 'output': 0, 'page_size': 15,
        'show_obs_wl': 1, 'show_calc_wl': 1, 'order_out': 0, 'show_av': 2, 'tsb_value': 0,
        'A_out': 0, 'intens_out': 'on', 'allowed_out': 1, 'forbid_out': 1,
    }
    return NIST_URL + '?' + urllib.parse.urlencode(q)


def nist_lines(raw, spectrum, lo=370, hi=770):
    """[(nm, intensity or None, 'obs'|'ritz')] for one spectrum, air wavelengths."""
    fname = os.path.join(raw, 'nist_' + spectrum.replace(' ', '_') + '.csv')
    text = fetch(nist_query(spectrum, lo, hi), fname).decode('utf-8', 'replace')
    rows = list(csv.reader(io.StringIO(text)))
    head = rows[0]
    if not head or head[0] != 'obs_wl_air(nm)' or head[1] != 'ritz_wl_air(nm)' or head[2] != 'intens':
        sys.exit(f'unexpected NIST output for {spectrum}: {head[:4]}')
    out = []
    for r in rows[1:]:
        c = [re.sub(r'^="?|"$', '', x.strip()).strip('"') for x in r[:3]]
        obs, ritz, inten = c
        wl, kind = (obs, 'obs') if obs else (ritz, 'ritz')
        try:
            wl = float(wl)
        except ValueError:
            continue
        m = re.match(r'\d+(\.\d+)?', inten)
        out.append((wl, float(m.group()) if m else None, kind))
    return out


